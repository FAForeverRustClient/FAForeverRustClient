//! IPC contract: the anti-drift boundary.
//!
//! Generates the TypeScript definitions for every type that crosses the Tauri
//! boundary ([`AppState`], [`AppCommand`], [`AppEvent`] and everything they
//! reference, and what the shell's own commands take and answer with) straight
//! from the Rust source of truth. The frontend imports the result; no
//! cross-boundary type is ever hand-written (ARCHITECTURE.md §3.7).
//!
//! The types only the shell builds are defined here, in [`shell`], because
//! this crate cannot see the shell's.
//!
//! It also writes [`AppState::default()`] out as the frontend store's starting
//! state, so that is not hand-written either.
//!
//! Run `cargo run -p faf-ipc --bin export-bindings` to (re)generate
//! `ui/src/ipc/bindings.ts` and `ui/src/ipc/initialState.ts`. The CI
//! bindings-drift job fails if either is stale.

pub mod shell;

use faf_domain::native::{MapAnalysis, MarkedMapPreview, UnitIconNames};
use faf_domain::state::{ContributionProblem, DraftRejection, ReviewProblem};
use faf_domain::{AppCommand, AppEvent, AppState};
use specta::Types;
use specta_typescript::Typescript;

use shell::{
    FrontendMessage, LogPreview, NotificationDisplay, NotificationPopupBatch, PickRequest,
    VersionedSnapshot, WebviewEngine,
};

pub const HEADER: &str = "\
// AUTO-GENERATED by `cargo run -p faf-ipc --bin export-bindings`.
// Source of truth: crates/faf-domain. DO NOT EDIT BY HAND.
";

/// Render the TypeScript bindings for the whole IPC surface.
///
/// Registering the three root types pulls in every referenced slice type
/// (SessionState, SessionEvent, …) transitively.
///
/// The rest have to be named explicitly because they are reachable from none
/// of the three. Some are the *return* types of pure domain rules the frontend
/// owns a twin of, pinned by the conformance fixture (see
/// `ui/src/shared/rules/trainingRules.ts` and `tourneyRules.ts`); the others
/// are what the event stream, the snapshot and the shell's native commands
/// (`ui/src/ipc/client.ts`, `native.ts`) carry beside the state. Registering
/// them here is what keeps the frontend from having to hand-write them, which
/// is the one thing this crate exists to prevent.
pub fn typescript_bindings() -> Result<String, specta_typescript::Error> {
    let types = Types::default()
        .register::<AppState>()
        .register::<AppCommand>()
        .register::<AppEvent>()
        .register::<ReviewProblem>()
        .register::<ContributionProblem>()
        .register::<DraftRejection>()
        .register::<FrontendMessage>()
        .register::<VersionedSnapshot>()
        .register::<LogPreview>()
        .register::<WebviewEngine>()
        .register::<NotificationPopupBatch>()
        .register::<NotificationDisplay>()
        .register::<PickRequest>()
        .register::<MapAnalysis>()
        .register::<MarkedMapPreview>()
        .register::<UnitIconNames>();

    let body = Typescript::default().export(&types, specta_serde::Format)?;
    // Specta currently emits a space after several multiline union separators.
    // Keep the checked-in contract deterministic and `git diff --check` clean.
    let body = body
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n");
    let delta_kinds = serde_json::to_string(faf_domain::frontend::FrontendUpdate::DELTA_KINDS)
        .expect("the static delta policy must serialize");
    Ok(format!(
        "{HEADER}\n{body}\nexport const DELTA_EVENT_KINDS = {delta_kinds} as const;\n"
    ))
}

pub const INITIAL_STATE_HEADER: &str = "\
// AUTO-GENERATED by `cargo run -p faf-ipc --bin export-bindings`.
// Source of truth: `AppState::default()` in crates/faf-domain. DO NOT EDIT BY HAND.
";

/// Render [`AppState::default()`] as the state the frontend store starts from,
/// until the first backend snapshot replaces it.
///
/// The literal is typed as `AppState`, so the compiler checks it against the
/// bindings written beside it. The output must not depend on hash order or
/// the platform, because CI regenerates it on Linux and diffs it: today every
/// map in the default state is empty.
pub fn typescript_initial_state() -> Result<String, serde_json::Error> {
    let state = serde_json::to_string_pretty(&AppState::default())?;
    Ok(format!(
        "{INITIAL_STATE_HEADER}\nimport type {{ AppState }} from \"./bindings\";\n\n\
         export const INITIAL_STATE: AppState = {state};\n"
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn bindings_contain_root_types() {
        let ts = typescript_bindings().expect("export should succeed");
        for ty in ["AppState", "AppCommand", "AppEvent", "SessionState"] {
            assert!(ts.contains(ty), "bindings missing `{ty}`:\n{ts}");
        }
    }

    #[test]
    fn bindings_have_no_trailing_whitespace() {
        let ts = typescript_bindings().expect("export should succeed");
        assert!(ts.lines().all(|line| line.trim_end() == line));
    }

    #[test]
    fn initial_state_does_not_depend_on_hash_order() {
        // Each render builds its own default state, and each `HashMap` in it
        // its own hash seed, so a populated map would come out reordered.
        let ts = typescript_initial_state().expect("default state should serialise");
        assert!(ts.contains("export const INITIAL_STATE: AppState = {"));
        assert_eq!(
            ts,
            typescript_initial_state().expect("default state should serialise")
        );
    }
}
