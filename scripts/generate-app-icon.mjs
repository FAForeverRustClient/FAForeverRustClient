// Composes the native icon from the repository's one piece of brand artwork.
//
// `ui/public/assets/faflogo.svg` is the source of truth: the webview masks it
// per theme (ui/src/design-system/BrandMark.tsx) and this script wraps the
// same file into `app-icon.svg`, which `tauri icon` then fans out across
// src-tauri/icons. Regenerate with `pnpm icons` whenever the SVG changes, so the
// window, the taskbar and the installer cannot drift apart again.
//
// The wordmark is white on transparency and roughly 2:1, so it spans the width
// of a square canvas, centred, rather than being stretched to fill one. The OS
// draws the icon on whatever the taskbar happens to be, and white alone
// vanishes on a light one, so the mark carries a dark outline: a copy of it
// stroked black, laid behind it. That copy inherits its stroke, so the outline
// holds only while the artwork is filled shapes without strokes of their own.
//
// The result stays vector so that `tauri icon` draws every size from the
// shapes themselves, which keeps the 16 and 24 px icons sharper than shrinking
// one large bitmap would.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const source = resolve(root, "ui/public/assets/faflogo.svg");
const target = resolve(root, "app-icon.svg");

const CANVAS = 1024;
const OUTLINE = 48; // About a pixel at 24px, the taskbar's size at 100% scaling.
// The artwork's viewBox spans the canvas, outline included. The mark may sit a
// little inside its own viewBox, so a thin margin can remain at the edges.
const MARK_WIDTH = CANVAS - 2 * OUTLINE;

if (!existsSync(source)) {
  console.error(`Brand artwork is missing: ${source}`);
  process.exit(1);
}

const artwork = readFileSync(source, "utf8");
const opening = artwork.match(/<svg\b[^>]*>/);
const viewBox = opening?.[0]
  .match(/\bviewBox="([^"]+)"/)?.[1]
  .trim()
  .split(/[\s,]+/)
  .map(Number);

if (!opening || viewBox?.length !== 4 || viewBox.some(Number.isNaN)) {
  console.error(`Brand artwork has no viewBox to size the icon from: ${source}`);
  process.exit(1);
}

const [minX, minY, width, height] = viewBox;
const body = artwork.slice(opening.index + opening[0].length, artwork.lastIndexOf("</svg>"));
const scale = MARK_WIDTH / width;
const top = (CANVAS - height * scale) / 2;
const round = (value) => Number(value.toFixed(3));
const place = `translate(${round(OUTLINE - minX * scale)} ${round(top - minY * scale)}) scale(${round(scale)})`;
// A stroke is centred on the edge, so twice the outline shows OUTLINE outside it.
const stroke = round((2 * OUTLINE) / scale);

writeFileSync(
  target,
  `<!-- Generated by scripts/generate-app-icon.mjs from ui/public/assets/faflogo.svg. Do not edit by hand. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${CANVAS} ${CANVAS}">
  <defs><g id="faf-mark">${body}</g></defs>
  <use href="#faf-mark" transform="${place}" stroke="#000" stroke-width="${stroke}" stroke-linejoin="round"/>
  <use href="#faf-mark" transform="${place}"/>
</svg>
`,
);

console.log("Wrote app-icon.svg from faflogo.svg.");
console.log("Now fan it out across the native icon set:  pnpm tauri icon ./app-icon.svg");
